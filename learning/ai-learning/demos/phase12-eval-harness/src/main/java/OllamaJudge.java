import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * AWS three-layer framework, layer 2b: trajectory quality, LLM-as-judge.
 *
 * Minimal single-shot Ollama {@code /api/chat} client, re-wrapped from
 * {@code phase8-autonomous/OllamaClient.java} the same way THAT file says it
 * was re-wrapped from phase4's -- every phase in this repo is an
 * independent Maven module by convention (see phase8's README header), so a
 * small duplicated HTTP client is the established pattern here, not an
 * oversight.
 *
 * Bias-mitigation note (this IS the point of this class existing): AWS
 * Module 3 flags self-reinforcement bias -- a judge model scores its own
 * family's output more favorably. phase8's traces were generated by
 * qwen2.5-coder:7b (CODING step) with llama3.2:3b doing PLANNING/REVIEW.
 * This harness deliberately judges with model(s) that are NOT
 * qwen2.5-coder -- see JudgeVarianceTest, which runs the SAME trajectory
 * through two different judge models and records where they disagree
 * rather than picking one and hiding the other's opinion.
 */
public final class OllamaJudge {

    private static final ObjectMapper JSON = new ObjectMapper();
    private static final Pattern JSON_OBJECT = Pattern.compile("\\{.*}", Pattern.DOTALL);

    public record Verdict(String model, int score, String reasoning, boolean parsedCleanly, String rawResponse) {
    }

    private final String baseUrl;
    private final String model;
    private final HttpClient http = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(5)).build();

    public OllamaJudge(String model) {
        this("http://localhost:11434", model);
    }

    public OllamaJudge(String baseUrl, String model) {
        this.baseUrl = baseUrl;
        this.model = model;
    }

    public String model() {
        return model;
    }

    /** Quick reachability probe -- used by tests to skip (not fail) the judge tests when no local Ollama is running. */
    public static boolean isReachable(String baseUrl) {
        try {
            HttpClient probe = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(2)).build();
            HttpRequest req = HttpRequest.newBuilder().uri(URI.create(baseUrl + "/api/tags"))
                    .timeout(Duration.ofSeconds(2)).GET().build();
            HttpResponse<String> resp = probe.send(req, HttpResponse.BodyHandlers.ofString());
            return resp.statusCode() == 200;
        } catch (Exception e) {
            return false;
        }
    }

    /** True if Ollama is reachable AND has {@code model} pulled. */
    public static boolean hasModel(String baseUrl, String model) {
        try {
            HttpClient probe = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(2)).build();
            HttpRequest req = HttpRequest.newBuilder().uri(URI.create(baseUrl + "/api/tags"))
                    .timeout(Duration.ofSeconds(2)).GET().build();
            HttpResponse<String> resp = probe.send(req, HttpResponse.BodyHandlers.ofString());
            if (resp.statusCode() != 200) {
                return false;
            }
            JsonNode root = JSON.readTree(resp.body());
            for (JsonNode m : root.path("models")) {
                String name = m.path("name").asText("");
                if (name.equals(model) || name.startsWith(model + ":")) {
                    return true;
                }
            }
            return false;
        } catch (Exception e) {
            return false;
        }
    }

    private static final String RUBRIC = """
            You are grading the QUALITY of an autonomous coding agent's trajectory, not the code itself.
            The trajectory is a sequence of state-machine steps (planning, coding, review, testing, gate
            decisions) captured from a real run. Score 1-5 on how well the trajectory followed sound
            agentic practice: did it plan before coding, test before shipping, retry sensibly on failure
            instead of thrashing, and reach a clean terminal state (either a shipped PR or a deliberate
            escalation) without wasted or repeated steps beyond what retries required.

            Respond with ONLY a single JSON object, no prose outside it, in exactly this shape:
            {"score": <integer 1-5>, "reasoning": "<one or two sentences>"}
            """;

    public Verdict judge(RunTrace trace) {
        String summary = summarize(trace);
        ObjectNode body = JSON.createObjectNode();
        body.put("model", model);
        body.put("stream", false);
        ArrayNode messages = body.putArray("messages");
        messages.addObject().put("role", "system").put("content", RUBRIC);
        messages.addObject().put("role", "user").put("content", summary);
        body.putObject("options").put("temperature", 0.1);

        try {
            HttpRequest req = HttpRequest.newBuilder()
                    .uri(URI.create(baseUrl + "/api/chat"))
                    .timeout(Duration.ofMinutes(2))
                    .header("Content-Type", "application/json")
                    .POST(HttpRequest.BodyPublishers.ofString(JSON.writeValueAsString(body)))
                    .build();
            HttpResponse<String> resp = http.send(req, HttpResponse.BodyHandlers.ofString());
            if (resp.statusCode() != 200) {
                throw new RuntimeException("Ollama HTTP " + resp.statusCode() + ": " + resp.body());
            }
            JsonNode root = JSON.readTree(resp.body());
            String text = root.path("message").path("content").asText("").strip();
            return parseVerdict(text);
        } catch (IOException | InterruptedException e) {
            if (e instanceof InterruptedException) {
                Thread.currentThread().interrupt();
            }
            return new Verdict(model, -1, "judge call failed: " + e.getMessage(), false, "");
        }
    }

    private Verdict parseVerdict(String rawText) {
        Matcher m = JSON_OBJECT.matcher(rawText);
        if (!m.find()) {
            return new Verdict(model, -1, "no JSON object found in judge response", false, rawText);
        }
        try {
            JsonNode parsed = JSON.readTree(m.group());
            int score = parsed.path("score").asInt(-1);
            String reasoning = parsed.path("reasoning").asText("");
            return new Verdict(model, score, reasoning, true, rawText);
        } catch (Exception e) {
            return new Verdict(model, -1, "failed to parse judge JSON: " + e.getMessage(), false, rawText);
        }
    }

    /** Compact, deterministic textual summary of the trajectory -- what the judge model actually sees, not the raw JSONL. */
    static String summarize(RunTrace trace) {
        StringBuilder sb = new StringBuilder();
        sb.append("Trajectory for run ").append(trace.runId()).append(":\n");
        for (JsonNode e : trace.events()) {
            String event = e.path("event").asText("?");
            switch (event) {
                case "step" -> sb.append("- step: ").append(e.path("step").asText())
                        .append(" (tokensIn=").append(e.path("tokensIn").asInt())
                        .append(", tokensOut=").append(e.path("tokensOut").asInt())
                        .append(", latencyMs=").append(e.path("latencyMs").asLong()).append(")\n");
                case "gate_decision" -> sb.append("- gate_decision: ").append(e.path("gate").asText())
                        .append(" approved=").append(e.path("approved").asBoolean()).append("\n");
                case "test_run" -> sb.append("- test_run: passed=").append(e.path("passed").asBoolean())
                        .append(" durationMs=").append(e.path("durationMs").asLong()).append("\n");
                case "file_written" -> sb.append("- file_written: ").append(e.path("path").asText()).append("\n");
                case "run_summary" -> sb.append("- run_summary: outcome=").append(e.path("outcome").asText())
                        .append(" steps=").append(e.path("steps").asInt())
                        .append(" testRuns=").append(e.path("testRuns").asInt())
                        .append(" testPasses=").append(e.path("testPasses").asInt()).append("\n");
                default -> sb.append("- ").append(event).append("\n");
            }
        }
        return sb.toString();
    }
}
